<#
.SYNOPSIS
    Creates the release signing key for Browser Picker.

.DESCRIPTION
    Generates a keystore and the matching `keystore.properties` file that
    `app/build.gradle.kts` reads to sign the release variant.

    Both the keystore and `keystore.properties` are git-ignored on purpose:
    the key must never end up in the repository.

    IMPORTANT: back up the generated keystore somewhere safe. The Android
    signature is bound to it — losing it means you can no longer ship an
    update for an app that is already installed on user devices.

.EXAMPLE
    ./scripts/create-release-keystore.ps1
    ./gradlew assembleRelease
#>
[CmdletBinding()]
param(
    [string]$Alias = 'browserpicker',
    [string]$StoreFile = 'browserpicker-release.jks',
    [int]$ValidityDays = 10000,
    [switch]$Force
)

$ErrorActionPreference = 'Stop'

$projectRoot = Split-Path -Parent $PSScriptRoot
$keystorePath = Join-Path $projectRoot $StoreFile
$propertiesPath = Join-Path $projectRoot 'keystore.properties'

function Get-KeytoolPath {
    $command = Get-Command 'keytool' -ErrorAction SilentlyContinue
    if ($command) { return $command.Source }

    $javaHome = $env:JAVA_HOME
    if (-not $javaHome) {
        $java = Get-Command 'java' -ErrorAction SilentlyContinue
        if ($java) { $javaHome = Split-Path -Parent (Split-Path -Parent $java.Source) }
    }
    if ($javaHome) {
        $candidate = Join-Path $javaHome 'bin\keytool.exe'
        if (Test-Path -LiteralPath $candidate) { return $candidate }
        $candidate = Join-Path $javaHome 'bin\keytool'
        if (Test-Path -LiteralPath $candidate) { return $candidate }
    }
    throw 'keytool was not found. Install a JDK 17 or set JAVA_HOME.'
}

function New-RandomPassword {
    $bytes = New-Object byte[] 24
    [System.Security.Cryptography.RandomNumberGenerator]::Fill($bytes)
    return [Convert]::ToBase64String($bytes).Replace('+', 'A').Replace('/', 'B').Replace('=', '')
}

if ((Test-Path -LiteralPath $keystorePath) -and -not $Force) {
    throw "Keystore '$keystorePath' already exists. Use -Force to overwrite it."
}

$keytool = Get-KeytoolPath
$password = New-RandomPassword

Write-Host "Creating keystore: $keystorePath"
& $keytool -genkeypair -v `
    -keystore $keystorePath `
    -storetype PKCS12 `
    -alias $Alias `
    -keyalg RSA `
    -keysize 2048 `
    -validity $ValidityDays `
    -storepass $password `
    -keypass $password `
    -dname 'CN=Browser Picker, OU=Release, O=Browser Picker, L=, ST=, C='
if ($LASTEXITCODE -ne 0) { throw "keytool failed with exit code $LASTEXITCODE" }

$properties = @"
# Generated by scripts/create-release-keystore.ps1
# Keep this file out of version control and back it up together with the keystore.
storeFile=$StoreFile
storePassword=$password
keyAlias=$Alias
keyPassword=$password
"@
[System.IO.File]::WriteAllText($propertiesPath, $properties, (New-Object System.Text.UTF8Encoding($false)))

Write-Host ''
Write-Host 'Done.'
Write-Host "  keystore : $keystorePath"
Write-Host "  properties: $propertiesPath"
Write-Host ''
Write-Host 'Next step:  ./gradlew assembleRelease'
Write-Host 'Back up both files - the keystore is what makes future updates installable.'